    /**
     * C++ literal for a float constant.
     *
     * <p>{@code Float.toString} yields "Infinity" / "-Infinity" / "NaN", none of which are valid
     * C++ tokens — emitting them produced {@code Infinityf} and broke the whole sink translation
     * unit (one bad constant fails the entire DLL, and with it every sunk method). The <cmath>
     * macros INFINITY/NAN are always in scope in the generated unit.</p>
     */
    private static String floatLiteral(float value) {
        if (Float.isNaN(value)) {
            return "NAN";
        }
        if (value == Float.POSITIVE_INFINITY) {
            return "INFINITY";
        }
        if (value == Float.NEGATIVE_INFINITY) {
            return "(-INFINITY)";
        }
        return Float.toString(value) + "f";
    }

    /** C++ literal for a double constant; same Infinity/NaN problem as {@link #floatLiteral}. */
    private static String doubleLiteral(double value) {
        if (Double.isNaN(value)) {
            return "NAN";
        }
        if (value == Double.POSITIVE_INFINITY) {
            return "INFINITY";
        }
        if (value == Double.NEGATIVE_INFINITY) {
            return "(-INFINITY)";
        }
        return Double.toString(value);
    }

    private static String intCompare(int op) {
        return switch (op) {
            case Opcodes.IFEQ, Opcodes.IF_ICMPEQ -> "==";
            case Opcodes.IFNE, Opcodes.IF_ICMPNE -> "!=";
            case Opcodes.IFLT, Opcodes.IF_ICMPLT -> "<";
            case Opcodes.IFGE, Opcodes.IF_ICMPGE -> ">=";
            case Opcodes.IFGT, Opcodes.IF_ICMPGT -> ">";
            case Opcodes.IFLE, Opcodes.IF_ICMPLE -> "<=";
            default -> throw new IllegalStateException("op " + op);
        };
    }

