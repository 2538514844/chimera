    private static boolean primitiveOrReferenceDescriptor(String methodDesc) {
        Type ret = Type.getReturnType(methodDesc);
        boolean retOk = ret.getSort() == Type.VOID || isPrimitive(ret)
                || ret.getSort() == Type.OBJECT || ret.getSort() == Type.ARRAY;
        if (!retOk) {
            return false;
        }
        for (Type arg : Type.getArgumentTypes(methodDesc)) {
            if (!isPrimitive(arg) && arg.getSort() != Type.OBJECT && arg.getSort() != Type.ARRAY) {
                return false;
            }
        }
        return true;
    }

    private static boolean isPrimitive(Type type) {
        return switch (type.getSort()) {
            case Type.BOOLEAN, Type.BYTE, Type.CHAR, Type.SHORT,
                 Type.INT, Type.LONG, Type.FLOAT, Type.DOUBLE -> true;
            default -> false;
        };
    }

    /**
     * C-3: literals carry modified UTF-8 bytes (invisible-renamed names, non-ASCII strings).
     * The previous one-byte-per-char escaping produced invalid JNI name tables.
     */
    private static String cLiteral(String s) {
        return dev.chimera.core.CppLiteral.escape(s);
    }

    private static String opcodeName(AbstractInsnNode insn) {
        int op = insn.getOpcode();
        if (op == Opcodes.GETFIELD || op == Opcodes.PUTFIELD || op == Opcodes.GETSTATIC
                || op == Opcodes.PUTSTATIC) {
            return "field-ref " + ((FieldInsnNode) insn).owner + "." + ((FieldInsnNode) insn).name;
        }
        if (op >= Opcodes.INVOKEVIRTUAL && op <= Opcodes.INVOKEINTERFACE) {
            return "call " + ((MethodInsnNode) insn).owner + "." + ((MethodInsnNode) insn).name;
        }
        if (insn instanceof InsnNode) {
            return "insn";
        }
        return insn.getClass().getSimpleName();
    }
