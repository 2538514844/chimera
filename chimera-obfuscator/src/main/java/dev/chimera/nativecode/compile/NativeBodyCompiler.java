        private void emitIntDiv(int handler) {
            b.append("    if (st[sp - 1].i == 0) { env->ThrowNew(env->FindClass(\"").append(ARITH).append("\"), \"/ by zero\"); ");
            emitThrowRoute(handler);
            b.append(" }\n");
            b.append("    sp--; { jint x = st[sp - 1].i, y = st[sp].i; st[sp - 1].i = (x == INT32_MIN && y == -1) ? INT32_MIN : (jint)((jlong)x / (jlong)y); }\n");
        }

        private void emitIntRem(int handler) {
            b.append("    if (st[sp - 1].i == 0) { env->ThrowNew(env->FindClass(\"").append(ARITH).append("\"), \"/ by zero\"); ");
            emitThrowRoute(handler);
            b.append(" }\n");
            b.append("    sp--; { jint x = st[sp - 1].i, y = st[sp].i; st[sp - 1].i = (x == INT32_MIN && y == -1) ? 0 : (jint)((jlong)x % (jlong)y); }\n");
        }

        private void emitLongDiv(int handler) {
            b.append("    if (st[sp - 1].j == 0) { env->ThrowNew(env->FindClass(\"").append(ARITH).append("\"), \"/ by zero\"); ");
            emitThrowRoute(handler);
            b.append(" }\n");
            b.append("    sp--; { jlong x = st[sp - 1].j, y = st[sp].j; st[sp - 1].j = (x == INT64_MIN && y == -1) ? INT64_MIN : (x / y); }\n");
        }

        private void emitLongRem(int handler) {
            b.append("    if (st[sp - 1].j == 0) { env->ThrowNew(env->FindClass(\"").append(ARITH).append("\"), \"/ by zero\"); ");
            emitThrowRoute(handler);
            b.append(" }\n");
            b.append("    sp--; { jlong x = st[sp - 1].j, y = st[sp].j; st[sp - 1].j = (x == INT64_MIN && y == -1) ? 0 : (x % y); }\n");
        }

        private void emitThrowRoute(int handler) {
            if (handler >= 0) {
                b.append("sp = 0; st[sp++].l = env->ExceptionOccurred(); env->ExceptionClear(); goto L")
                        .append(labels.get(tryCatch.get(handler).handler)).append(";");
            } else {
                b.append("return ").append(defaultReturn).append(";");
            }
        }

        private void emitExceptionRoute(int handler) {
            b.append("    if (env->ExceptionCheck()) { ");
            if (handler >= 0) {
                b.append("sp = 0; st[sp++].l = env->ExceptionOccurred(); env->ExceptionClear(); goto L")
                        .append(labels.get(tryCatch.get(handler).handler)).append(";");
            } else {
                b.append("return ").append(defaultReturn).append(";");
            }
            b.append(" }\n");
        }

        private void emitTableSwitch(TableSwitchInsnNode sw) {
            b.append("    sp--; switch (st[sp].i) {\n");
            for (int i = 0; i < sw.labels.size(); i++) {
                b.append("        case ").append(sw.min + i).append(": goto L")
                        .append(labels.get(sw.labels.get(i))).append(";\n");
            }
            b.append("        default: goto L").append(labels.get(sw.dflt)).append(";\n    }\n");
        }

        private void emitLookupSwitch(LookupSwitchInsnNode sw) {
            b.append("    sp--; switch (st[sp].i) {\n");
            for (int i = 0; i < sw.keys.size(); i++) {
                b.append("        case ").append(sw.keys.get(i)).append(": goto L")
                        .append(labels.get(sw.labels.get(i))).append(";\n");
            }
            b.append("        default: goto L").append(labels.get(sw.dflt)).append(";\n    }\n");
        }

