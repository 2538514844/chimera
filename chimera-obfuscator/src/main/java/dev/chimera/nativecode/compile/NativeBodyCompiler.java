        /** 同时接受内部名（java/lang/String）与描述符（Ljava/lang/String;、[I）。 */
        private static String findClassArg(String desc) {
            if (desc.startsWith("[")) {
                return Type.getType(desc).getDescriptor();
            }
            if (desc.startsWith("L") && desc.endsWith(";")) {
                return Type.getType(desc).getInternalName();
            }
            return desc;
        }

        private void classCacheStatements(String findArg, String sfx, int handler) {
            b.append("      static jclass cls_").append(sfx).append(" = nullptr;\n");
            b.append("      if (cls_").append(sfx).append(" == nullptr) { jclass _l").append(sfx)
                    .append(" = chimera_sink_resolve(env, \"").append(cLiteral(findArg)).append("\"); if (_l").append(sfx)
                    .append(" != nullptr) { cls_").append(sfx).append(" = (jclass)env->NewGlobalRef(_l").append(sfx)
                    .append("); env->DeleteLocalRef(_l").append(sfx).append("); } }\n");
            emitExceptionRoute(handler);
        }

        private void emitClassLiteral(String desc, int handler) {
            String sfx = Integer.toString(tmpCounter++);
            b.append("    {\n");
            classCacheStatements(findClassArg(desc), sfx, handler);
            b.append("      st[sp++].l = (jobject)cls_").append(sfx).append("; }\n");
        }

        private void emitNew(TypeInsnNode insn, int handler) {
            String sfx = Integer.toString(tmpCounter++);
            b.append("    {\n");
            classCacheStatements(insn.desc, sfx, handler);
            b.append("      jobject _o").append(sfx).append(" = env->AllocObject(cls_").append(sfx).append(");\n");
            emitExceptionRoute(handler);
            b.append("      st[sp++].l = _o").append(sfx).append("; }\n");
        }

        private void emitANewArray(TypeInsnNode insn, int handler) {
            String sfx = Integer.toString(tmpCounter++);
            b.append("    { jint _n").append(sfx).append(" = st[--sp].i;\n");
            b.append("      if (_n").append(sfx).append(" < 0) { env->ThrowNew(env->FindClass(\"").append(NASE).append("\"), nullptr); ");
            emitThrowRoute(handler);
            b.append(" }\n");
            classCacheStatements(insn.desc, sfx, handler);
            b.append("      jobject _a").append(sfx).append(" = env->NewObjectArray(_n").append(sfx)
                    .append(", cls_").append(sfx).append(", nullptr);\n");
            emitExceptionRoute(handler);
            b.append("      st[sp++].l = _a").append(sfx).append("; }\n");
        }

        private void emitCheckcast(TypeInsnNode insn, int handler) {
            String sfx = Integer.toString(tmpCounter++);
            b.append("    {\n");
            classCacheStatements(insn.desc, sfx, handler);
            b.append("      jobject _o").append(sfx).append(" = st[sp - 1].l;\n");
            b.append("      if (_o").append(sfx).append(" != nullptr && env->IsInstanceOf(_o").append(sfx)
                    .append(", cls_").append(sfx).append(") == JNI_FALSE) { env->ThrowNew(env->FindClass(\"java/lang/ClassCastException\"), nullptr); ");
            emitThrowRoute(handler);
            b.append(" } }\n");
        }

        private void emitInstanceof(TypeInsnNode insn, int handler) {
            String sfx = Integer.toString(tmpCounter++);
            b.append("    {\n");
            classCacheStatements(insn.desc, sfx, handler);
            b.append("      jobject _o").append(sfx).append(" = st[--sp].l;\n");
            b.append("      st[sp++].i = (_o").append(sfx).append(" == nullptr) ? 0 : (env->IsInstanceOf(_o")
                    .append(sfx).append(", cls_").append(sfx).append(") ? 1 : 0); }\n");
        }

        private void emitInvoke(MethodInsnNode mi, int handler) {
            String sfx = Integer.toString(tmpCounter++);
            boolean isStaticCall = mi.getOpcode() == Opcodes.INVOKESTATIC;
            boolean isSpecial = mi.getOpcode() == Opcodes.INVOKESPECIAL;
            b.append("    { static jclass cls_").append(sfx).append(" = nullptr; static jmethodID mid_")
                    .append(sfx).append(" = nullptr;\n");
            b.append("      if (cls_").append(sfx).append(" == nullptr) { jclass _l").append(sfx)
                    .append(" = chimera_sink_resolve(env, \"").append(cLiteral(mi.owner)).append("\"); if (_l").append(sfx)
                    .append(" != nullptr) { cls_").append(sfx).append(" = (jclass)env->NewGlobalRef(_l").append(sfx)
                    .append("); env->DeleteLocalRef(_l").append(sfx).append("); } }\n");
            b.append("      if (mid_").append(sfx).append(" == nullptr && cls_").append(sfx).append(" != nullptr) mid_")
                    .append(sfx).append(" = env->").append(isStaticCall ? "GetStaticMethodID" : "GetMethodID")
                    .append("(cls_").append(sfx).append(", \"").append(cLiteral(mi.name)).append("\", \"")
                    .append(cLiteral(mi.desc)).append("\");\n");
            emitExceptionRoute(handler);

            Type ret = Type.getReturnType(mi.desc);
            int n = Type.getArgumentTypes(mi.desc).length;
            int pop = n + (isStaticCall ? 0 : 1);
            String jniSuffix = jniCallSuffix(ret);
            String callName = (isStaticCall ? "CallStatic" : isSpecial ? "CallNonvirtual" : "Call")
                    + jniSuffix + "MethodA";
            b.append("      jvalue _a").append(sfx).append("[").append(Math.max(1, n)).append("];\n");
            if (n > 0) {
                b.append("      for (int _i").append(sfx).append(" = 0; _i").append(sfx).append(" < ").append(n)
                        .append("; ++_i").append(sfx).append(") _a").append(sfx).append("[_i").append(sfx)
                        .append("] = st[sp - ").append(n).append(" + _i").append(sfx).append("];\n");
            }
            if (!isStaticCall) {
                b.append("      jobject _r").append(sfx).append(" = st[sp - ").append(pop).append("].l;\n");
                b.append("      if (_r").append(sfx).append(" == nullptr) { env->ThrowNew(env->FindClass(\"")
                        .append(NPE).append("\"), nullptr); ");
                emitThrowRoute(handler);
                b.append(" }\n");
            }
            String callArgs;
            if (isStaticCall) {
                callArgs = "(cls_" + sfx + ", mid_" + sfx + ", _a" + sfx + ")";
            } else if (isSpecial) {
                callArgs = "(_r" + sfx + ", cls_" + sfx + ", mid_" + sfx + ", _a" + sfx + ")";
            } else {
                callArgs = "(_r" + sfx + ", mid_" + sfx + ", _a" + sfx + ")";
            }
            if (ret.getSort() == Type.VOID) {
                b.append("      env->").append(callName).append(callArgs).append(";\n");
                emitExceptionRoute(handler);
                b.append("      sp -= ").append(pop).append("; }\n");
            } else {
                b.append("      ").append(cValueType(ret)).append(" _v").append(sfx).append(" = env->")
                        .append(callName).append(callArgs).append(";\n");
                emitExceptionRoute(handler);
                b.append("      sp -= ").append(pop).append(";\n");
                b.append("      st[sp++].").append(slotField(ret)).append(" = _v").append(sfx).append("; }\n");
            }
        }

        private static String jniCallSuffix(Type ret) {
            return switch (ret.getSort()) {
                case Type.VOID -> "Void";
                case Type.BOOLEAN -> "Boolean";
                case Type.BYTE -> "Byte";
                case Type.CHAR -> "Char";
                case Type.SHORT -> "Short";
                case Type.INT -> "Int";
                case Type.LONG -> "Long";
                case Type.FLOAT -> "Float";
                case Type.DOUBLE -> "Double";
                case Type.ARRAY, Type.OBJECT -> "Object";
                default -> throw new UnsupportedInstruction(-1, "call return " + ret);
            };
        }

