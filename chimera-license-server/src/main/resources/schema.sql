CREATE TABLE IF NOT EXISTS accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account VARCHAR(190) NOT NULL UNIQUE,
    password_hash VARCHAR(190) NOT NULL,
    status VARCHAR(32) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    -- Stable per-licence identifier handed to the client (and signed in the v4 transcript). It is
    -- the value the per-licence watermark carries, so it must never change for an account.
    license_id VARCHAR(64)
);

-- Existing databases created before license_id was introduced. Rows are backfilled lazily by
-- LicenseStore.ensureLicenseId() on the next activation/heartbeat.
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS license_id VARCHAR(64);

CREATE TABLE IF NOT EXISTS devices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    hwid VARCHAR(190) NOT NULL,
    label VARCHAR(190),
    first_seen TIMESTAMP NOT NULL,
    last_seen TIMESTAMP NOT NULL,
    status VARCHAR(32) NOT NULL,
    -- Red team round 3, finding 3: `hwid` is a string the client writes, so anyone who learns a
    -- customer's 64 hex could activate on another machine. The real identity is now this column:
    -- the X25519 public key whose private half is sealed with DPAPI to that machine's Windows user.
    -- A copied `hwid` without the matching sealed key no longer activates.
    device_pub BYTEA,
    UNIQUE (account_id, hwid)
);

-- Existing databases created before device_pub was introduced. Rows are adopted lazily: the first
-- activation after the upgrade writes the presented key, then it is enforced.
ALTER TABLE devices ADD COLUMN IF NOT EXISTS device_pub BYTEA;

CREATE TABLE IF NOT EXISTS audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT,
    event VARCHAR(64) NOT NULL,
    hwid_hash VARCHAR(128),
    ip_hash VARCHAR(128),
    created_at TIMESTAMP NOT NULL
);

-- v4 auth state lives in dedicated tables: enabling v4 never changes v3 behaviour.
-- client_pub binds the activation-time X25519 public key to the session; nullable only so rows
-- created before this column existed can migrate (the first heartbeat adopts the presented key).
CREATE TABLE IF NOT EXISTS auth_v4_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token VARCHAR(190) NOT NULL UNIQUE,
    account_id BIGINT NOT NULL,
    hwid VARCHAR(190) NOT NULL,
    client_pub BYTEA,
    sequence BIGINT NOT NULL,
    issued_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL,
    revoked BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL
);

-- Existing databases created before client_pub was introduced. H2 runs in PostgreSQL mode here,
-- where the binary type is BYTEA (BLOB is rejected as an unknown type).
ALTER TABLE auth_v4_sessions ADD COLUMN IF NOT EXISTS client_pub BYTEA;

CREATE INDEX IF NOT EXISTS idx_auth_v4_sessions_account ON auth_v4_sessions(account_id, hwid);

-- kind='client_nonce' (replay table) and kind='server_nonce' (freshness table).
CREATE TABLE IF NOT EXISTS auth_v4_nonces (
    kind VARCHAR(32) NOT NULL,
    nonce_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    PRIMARY KEY (kind, nonce_hash)
);

-- One heartbeat request sequence may be consumed exactly once per session.
CREATE TABLE IF NOT EXISTS auth_v4_sequences (
    session_id BIGINT NOT NULL,
    sequence BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    PRIMARY KEY (session_id, sequence)
);

-- Token rotation history: a bearer token value is never issued twice.
CREATE TABLE IF NOT EXISTS auth_v4_tokens (
    token_hash VARCHAR(64) PRIMARY KEY,
    account_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL
);

-- Pre-registered hardware slots (onboarding flow, 2026-10-22): the operator adds the HWID a
-- customer sent over chat; the customer then self-registers an account and is bound to exactly
-- that machine. A reservation can be claimed once, which is what makes "register" safe to expose
-- without an invite code.
CREATE TABLE IF NOT EXISTS hwid_reservations (
    hwid VARCHAR(64) PRIMARY KEY,
    note VARCHAR(190),
    created_at TIMESTAMP NOT NULL,
    claimed_account_id BIGINT,
    claimed_at TIMESTAMP
);

-- Red team round 4 (source audit): the replay/sequence/token/audit tables only ever grew. One
-- client writes ~4300 rows a day (2 nonces + 1 sequence + 1 token + 1 audit per minute), so an H2
-- file database would grow without bound. These indexes back the retention sweep in SessionReaper.
CREATE INDEX IF NOT EXISTS idx_auth_v4_nonces_created ON auth_v4_nonces(created_at);
CREATE INDEX IF NOT EXISTS idx_auth_v4_sequences_created ON auth_v4_sequences(created_at);
CREATE INDEX IF NOT EXISTS idx_auth_v4_tokens_created ON auth_v4_tokens(created_at);
CREATE INDEX IF NOT EXISTS idx_audit_logs_created ON audit_logs(created_at);
CREATE INDEX IF NOT EXISTS idx_auth_v4_sessions_expires ON auth_v4_sessions(expires_at);
